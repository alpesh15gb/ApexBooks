# Legacy filename retained for callers; acceptance is now strictly local-only.
param(
    [switch]$PrepareQaSession,
    [string]$Serial='emulator-5554',
    [ValidatePattern('^[A-Za-z0-9_.]+$')][string]$TestClass,
    [string]$ApiOrigin='http://10.0.2.2:8012'
)
$ErrorActionPreference='Stop'
if($Serial -notmatch '^emulator-[0-9]+$'){throw 'Use a dedicated synthetic QA emulator.'}
$uri=[Uri]$ApiOrigin
if($uri.Scheme -ne 'http' -or $uri.Host -notin @('10.0.2.2','127.0.0.1','localhost') -or $uri.UserInfo -or $uri.Query -or $uri.Fragment -or $uri.AbsolutePath -ne '/'){
    throw 'Acceptance may only use an isolated local HTTP API. Hosted/production writes are forbidden.'
}
$repository=(Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$priorSerial=$env:ANDROID_SERIAL
try{
    $env:ANDROID_SERIAL=$Serial
    Push-Location (Join-Path $repository 'native\android')
    try{
        # Debug signing is generated by the Android toolchain. Never read release signing credentials.
        $arguments=@('--no-daemon',('-PapexApiOrigin='+$ApiOrigin.TrimEnd('/')),':app:connectedDebugAndroidTest')
        if($PrepareQaSession){$arguments+='-PapexKeepQaSession=true'}
        if($TestClass){$arguments+='-Pandroid.testInstrumentationRunnerArguments.class='+$TestClass}
        & .\gradlew.bat @arguments
        if($LASTEXITCODE -ne 0){throw 'Android local component acceptance failed.'}
        Write-Output 'Local synthetic acceptance passed. No release artifact or hosted data was changed.'
    }finally{Pop-Location}
}finally{$env:ANDROID_SERIAL=$priorSerial}
